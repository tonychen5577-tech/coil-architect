import os
import sys
import re
import shutil
import zipfile
import subprocess
from pathlib import Path
from datetime import datetime

# 确保在当前项目根目录执行
ROOT_DIR = Path(__file__).resolve().parent
os.chdir(ROOT_DIR)

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

CORE_MODULES = [
    "models",
    "physics_engine",
    "license_manager",
]


def find_vcvarsall() -> str:
    """自动探测 Visual Studio MSVC 编译环境"""
    candidates = [
        r"C:\Program Files\Microsoft Visual Studio\18\Community\VC\Auxiliary\Build\vcvarsall.bat",
        r"C:\Program Files\Microsoft Visual Studio\2022\Community\VC\Auxiliary\Build\vcvarsall.bat",
        r"C:\Program Files\Microsoft Visual Studio\2022\Professional\VC\Auxiliary\Build\vcvarsall.bat",
        r"C:\Program Files\Microsoft Visual Studio\2022\Enterprise\VC\Auxiliary\Build\vcvarsall.bat",
        r"C:\Program Files (x86)\Microsoft Visual Studio\2019\Community\VC\Auxiliary\Build\vcvarsall.bat",
        r"C:\Program Files (x86)\Microsoft Visual Studio\2019\BuildTools\VC\Auxiliary\Build\vcvarsall.bat",
    ]
    for p in candidates:
        if os.path.exists(p):
            return p
    return ""


def step1_cython_compilation() -> bool:
    """第一步：执行 Cython C 机器码转译与二进制编译"""
    print("\n" + "=" * 68)
    print("  [1/4] Cython 原生 C 机器码防逆向工程硬化编译流水线")
    print("=" * 68)

    setup_content = """# Auto-generated by build_exe.py
from setuptools import setup, Extension
from Cython.Build import cythonize

ext_modules = [
    Extension("src.core.models", ["src/core/models.py"]),
    Extension("src.core.physics_engine", ["src/core/physics_engine.py"]),
    Extension("src.core.license_manager", ["src/core/license_manager.py"]),
]

setup(
    name="coil_architect_core",
    ext_modules=cythonize(
        ext_modules,
        compiler_directives={"language_level": "3", "always_allow_keywords": True},
        quiet=True
    )
)
"""
    tmp_setup = ROOT_DIR / "_temp_build_cython.py"
    tmp_setup.write_text(setup_content, encoding="utf-8")

    vcvars = find_vcvarsall()
    cmd = f'python "{tmp_setup}" build_ext --inplace'
    if vcvars and sys.platform == "win32":
        print(f"[MSVC] 正在载入 MSVC 64位编译环境: {vcvars}")
        full_cmd = f'call "{vcvars}" x64 && {cmd}'
    else:
        full_cmd = cmd

    try:
        print(f"[Build] 执行核心模块编译...")
        subprocess.run(full_cmd, shell=True, check=True)
        print("[Build] Cython 原生动态库 (.pyd) 编译成功完成！")
    except Exception as e:
        print(f"[Error] Cython 编译遇到异常: {e}")
        return False
    finally:
        if tmp_setup.exists():
            tmp_setup.unlink(missing_ok=True)

    # 校验生成物
    core_dir = ROOT_DIR / "src" / "core"
    for mod in CORE_MODULES:
        pyds = list(core_dir.glob(f"{mod}.*.pyd"))
        if not pyds:
            print(f"[Warn] 未在 {core_dir} 检测到 {mod} 的 .pyd 动态库！")
            return False
        print(f"  ✓ 已生成 C 原生机器码: {pyds[0].name}")

    # 清理中间 C 源码
    for c_file in core_dir.glob("*.c"):
        try:
            c_file.unlink(missing_ok=True)
        except Exception:
            pass
    if (ROOT_DIR / "build").exists():
        shutil.rmtree(ROOT_DIR / "build", ignore_errors=True)

    return True


def step2_mask_python_sources() -> list:
    """第二步：打包前物理遮蔽 .py 源码文件，迫使打包器仅提取原生 .pyd 二进制"""
    print("\n" + "=" * 68)
    print("  [2/4] 核心算法与资产源码 (.py) 物理遮蔽隔离")
    print("=" * 68)
    masked = []
    core_dir = ROOT_DIR / "src" / "core"
    for mod in CORE_MODULES:
        py_file = core_dir / f"{mod}.py"
        bak_file = core_dir / f"{mod}.py.bak"
        if py_file.exists():
            if bak_file.exists():
                bak_file.unlink()
            py_file.rename(bak_file)
            masked.append((py_file, bak_file))
            print(f"  🔒 已遮蔽源码: {py_file.name} -> {bak_file.name}")
    return masked


def step2_unmask_python_sources(masked: list):
    """恢复被遮蔽的 .py 源码文件"""
    print("\n[Restore] 正在恢复工作区源码文件...")
    for py_file, bak_file in masked:
        if bak_file.exists():
            if py_file.exists():
                py_file.unlink()
            bak_file.rename(py_file)
            print(f"  🔓 已恢复源码: {py_file.name}")


def step3_pyinstaller_build() -> bool:
    """第三步：调用 PyInstaller 封装 Windows EXE 绿色包"""
    print("\n" + "=" * 68)
    print("  [3/4] PyInstaller 工业级绿色发布包封装流水线")
    print("=" * 68)

    dist_dir = ROOT_DIR / "dist"
    build_dir = ROOT_DIR / "build"
    app_entry = ROOT_DIR / "main.py"
    icon_file = ROOT_DIR / "resources" / "app_icon.ico"
    resources_dir = ROOT_DIR / "resources"

    # 清理旧生成物
    if (dist_dir / "Coil-Architect-Pro").exists():
        shutil.rmtree(dist_dir / "Coil-Architect-Pro", ignore_errors=True)
    if build_dir.exists():
        shutil.rmtree(build_dir, ignore_errors=True)

    cmd = [
        sys.executable, "-m", "PyInstaller",
        "--name=Coil-Architect-Pro",
        "--noconfirm",
        "--clean",
        "--onedir",
        "--windowed",
        f"--icon={icon_file}",
        f"--add-data={resources_dir}{os.pathsep}resources",
        "--hidden-import=src.core.models",
        "--hidden-import=src.core.physics_engine",
        "--hidden-import=src.core.license_manager",
        "--hidden-import=src.core.shortcut_helper",
        "--hidden-import=src.core.single_instance",
        "--hidden-import=src.core.ipc_manager",
        "--hidden-import=src.core.smart_dns",
        "--hidden-import=src.core.cloud_client",
        "--hidden-import=src.utils.logger",
        "--hidden-import=src.utils.file_association",
        "--hidden-import=PyQt6.QtNetwork",
        "--hidden-import=src.version",
        "--hidden-import=src.gui.about_dialog",
        "--hidden-import=src.gui.update_dialog",
        "--hidden-import=src.gui.cloud_config_dialog",
        "--hidden-import=src.gui.splash_screen",
        "--hidden-import=src.gui.icon_helper",
        "--hidden-import=src.gui.main_window",
        "--hidden-import=src.gui.activation_dialog",
        "--hidden-import=src.gui.styles",
        "--hidden-import=src.gui.utils",
        "--hidden-import=src.gui.widgets.coil_canvas",
        "--hidden-import=src.gui.widgets.comparison_drawer",
        "--hidden-import=src.gui.widgets.dfm_indicator",
        "--hidden-import=src.gui.widgets.metric_card",
        "--hidden-import=src.gui.widgets.slider_spin_box",
        "--hidden-import=src.export.report_excel",
        "--hidden-import=openpyxl",
        "--exclude-module=tkinter",
        "--exclude-module=unittest",
        "--exclude-module=IPython",
        "--exclude-module=jupyter",
        str(app_entry)
    ]

    print(f"[PyInstaller] 正在启动打包进程 (无黑框控制台 + 纯净依赖)...")
    res = subprocess.run(cmd, cwd=str(ROOT_DIR))
    if res.returncode != 0:
        print("[Fail] PyInstaller 打包失败！")
        return False

    out_exe = dist_dir / "Coil-Architect-Pro" / "Coil-Architect-Pro.exe"
    if not out_exe.exists():
        print(f"[Fail] 未找到目标生成文件: {out_exe}")
        return False

    print(f"\n[OK] 主执行程序构建成功: {out_exe}")
    return True


def step4_security_audit_and_zip() -> Path:
    """第四步：反编译防逆向安全审计与便携发布压缩包制作"""
    print("\n" + "=" * 68)
    print("  [4/4] 反编译安全审计与绿色分发归档制作")
    print("=" * 68)

    dist_dir = ROOT_DIR / "dist"
    app_dir = dist_dir / "Coil-Architect-Pro"

    # 安全审计：确保核心模块无 .py 源码遗留
    print("[Audit] 正在执行源码与字节码残留审计...")
    leaked_sources = []
    for root, _, files in os.walk(app_dir):
        for f in files:
            if f in ["physics_engine.py", "license_manager.py", "models.py"]:
                leaked_sources.append(os.path.join(root, f))
    if leaked_sources:
        print(f"  ❌ [ALERT] 发现源码泄漏: {leaked_sources}")
        raise RuntimeError("安全审计未通过：发现裸源码文件打包！")
    else:
        print("  ✓ [PASSED] 核心物理求解器、几何排布与商业授权核心 100% 为原生 C 机器码 (.pyd)！")
        print("  ✓ [PASSED] 无任何核心 .py 裸源码，彻底免疫 uncompyle6 / pycdc 等字节码逆向工具！")

    # 制作带时间戳与版本号的 Release ZIP 压缩包
    from src.version import APP_VERSION, APP_BUILD, get_git_commit
    git_hash = get_git_commit()
    date_str = datetime.now().strftime("%Y%m%d")
    zip_name = f"ANSV_Coil_Architect_Pro_{APP_VERSION}_{APP_BUILD}_{git_hash}.zip"
    zip_path = dist_dir / zip_name

    print(f"\n[Packaging] 正在打包发布压缩包: {zip_path.name} ...")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for f in app_dir.rglob("*"):
            if f.is_file():
                rel = f.relative_to(dist_dir).as_posix()
                zf.write(f, arcname=rel)

    zip_size_mb = zip_path.stat().st_size / (1024 * 1024)
    print(f"  ✓ 绿色便携发布包生成成功: {zip_path}")
    print(f"  ✓ 归档体积: {zip_size_mb:.2f} MB")

    # 制作增量升级补丁包 (仅含 EXE、核心 Cython .pyd 动态库与资源资产，体积仅 ~8.7 MB，节约 85%+ 流量)
    patch_name = f"ANSV_Coil_Architect_Pro_{APP_VERSION}_{APP_BUILD}_{git_hash}_Incremental_Patch.zip"
    patch_path = dist_dir / patch_name
    print(f"\n[Patching] 正在制作最小网络流量增量升级补丁包: {patch_path.name} ...")

    # 创建自动应用批处理
    apply_bat = app_dir / "一键应用增量补丁.bat"
    bat_content = """@echo off
chcp 65001 >nul
echo ========================================================
echo   ANSV Coil-Architect Pro 增量升级补丁自动应用脚本
echo ========================================================
echo 正在检测并关闭正在运行的程序实例...
taskkill /F /IM Coil-Architect-Pro.exe >nul 2>&1
timeout /t 1 /nobreak >nul
echo 正在复制增量文件覆盖更新...
xcopy /Y /E /I "_internal" "%~dp0_internal" >nul 2>&1
copy /Y "Coil-Architect-Pro.exe" "%~dp0" >nul 2>&1
echo 增量升级完成！已成功升级至最新版本。
pause
"""
    apply_bat.write_text(bat_content, encoding="utf-8")

    readme_txt = app_dir / "增量升级使用说明.txt"
    readme_content = f"""ANSV Coil-Architect Pro 增量升级补丁使用说明 ({APP_VERSION})
============================================================
【适用对象】已在运行历史版本的客户端工位机
【核心优势】仅需下载 ~8.7 MB，相比全量包节省 85% 以上网络带宽与等待时间！

【使用方法】
方法一 (一键覆盖):
  将本压缩包内的所有文件直接解压并覆盖到现有的 Coil-Architect-Pro 安装根目录。

方法二 (自动脚本):
  解压后双击运行「一键应用增量补丁.bat」，将自动完成安全覆盖升级。
============================================================
官方技术支持: ansv.net
"""
    readme_txt.write_text(readme_content, encoding="utf-8")

    with zipfile.ZipFile(patch_path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as pzf:
        # 1. exe
        pzf.write(app_dir / "Coil-Architect-Pro.exe", arcname="Coil-Architect-Pro.exe")
        # 2. _internal/src
        src_path = app_dir / "_internal" / "src"
        if src_path.exists():
            for f in src_path.rglob("*"):
                if f.is_file():
                    pzf.write(f, arcname=f.relative_to(app_dir).as_posix())
        # 3. _internal/resources
        res_path = app_dir / "_internal" / "resources"
        if res_path.exists():
            for f in res_path.rglob("*"):
                if f.is_file():
                    pzf.write(f, arcname=f.relative_to(app_dir).as_posix())
        # 4. bat & txt
        pzf.write(apply_bat, arcname="一键应用增量补丁.bat")
        pzf.write(readme_txt, arcname="增量升级使用说明.txt")

    # 清理临时文件
    apply_bat.unlink(missing_ok=True)
    readme_txt.unlink(missing_ok=True)

    patch_size_mb = patch_path.stat().st_size / (1024 * 1024)
    print(f"  ✓ 最小流量增量补丁包生成成功: {patch_path}")
    print(f"  ✓ 补丁归档体积: {patch_size_mb:.2f} MB (相比全量包节省 {(1 - patch_size_mb/zip_size_mb)*100:.1f}% 流量)")

    # 自动同步生成标准发布文件名 (对齐官方 OTA 与 GitHub Releases 下载索引)
    full_canonical = dist_dir / f"ANSV_Coil_Architect_Pro_{APP_VERSION}_Full.zip"
    patch_canonical = dist_dir / f"ANSV_Coil_Architect_Pro_{APP_VERSION}_Incremental_Patch.zip"
    shutil.copy2(zip_path, full_canonical)
    shutil.copy2(patch_path, patch_canonical)
    print(f"  ✓ 标准全量发布包同步生成: {full_canonical.name}")
    print(f"  ✓ 标准增量补丁包同步生成: {patch_canonical.name}")
    print("=" * 68)
    return zip_path, patch_path


def main():
    from src.version import APP_VERSION, APP_BUILD
    print("=" * 68)
    print("  ANSV 微型执行器与精密传动仿真验证平台")
    print(f"  Coil-Architect Pro ({APP_VERSION} · Build {APP_BUILD}) - 商业防反编译打包流程启动")
    print("=" * 68)

    # 严格校验构建号日期，确保每次升级均更新 APP_BUILD
    today_str = datetime.now().strftime("%Y%m%d")
    if today_str not in APP_BUILD:
        print(f"\n⚠️  [WARN] 检测到 src/version.py 中的 APP_BUILD ({APP_BUILD}) 未包含今日日期 ({today_str})！")
        print(f"⚠️  根据工业规范，每次发布新版本必须递增更新 APP_BUILD (如: {today_str}B1)，以便云端 OTA 精准识别。\n")
    else:
        print(f"  ✓ 构建号校验通过: {APP_BUILD} (包含今日日期 {today_str})")

    # 1. Cython 编译
    ok_cython = step1_cython_compilation()
    if not ok_cython:
        print("[Abort] Cython 机器码编译失败，终止打包。")
        sys.exit(1)

    # 2. 物理遮蔽源码
    masked_files = step2_mask_python_sources()

    build_success = False
    try:
        # 3. PyInstaller 绿色打包
        build_success = step3_pyinstaller_build()
    finally:
        # 无论成功失败，必须 100% 恢复工作区源码
        step2_unmask_python_sources(masked_files)

    if not build_success:
        print("\n[Abort] 打包未成功完成。")
        sys.exit(1)

    # 4. 安全审计与打包压缩 (包含全量独立包与最小流量增量补丁包)
    zip_file, patch_file = step4_security_audit_and_zip()
    print("\n🎉 [SUCCESS] 商业加固 EXE 绿色打包与防反编译工程审计全部顺利完成！")
    print(f"可执行文件目录: {ROOT_DIR / 'dist' / 'Coil-Architect-Pro'}")
    print(f"全量绿色发布包: {zip_file}")
    print(f"增量补丁发布包: {patch_file}")


if __name__ == "__main__":
    main()
