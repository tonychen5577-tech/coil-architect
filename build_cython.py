"""
Coil-Architect Pro - Cython C Machine Code Compilation Pipeline
将核心物理求解器、数据模型与商业授权安全核心转译编译为 Windows 原生 x86/x64 C 机器码动态库 (.pyd)
彻底免疫 uncompyle6 / pycdc 等字节码反编译工具 (严格依据规范 01.四 实现)
"""

import os
import sys
import shutil
import subprocess
from pathlib import Path

# 确保在当前项目根目录执行
_ROOT_DIR = Path(__file__).resolve().parent
os.chdir(_ROOT_DIR)


def find_vcvarsall() -> str:
    """自动探测 Visual Studio MSVC 编译环境变量入口"""
    candidates = [
        r"C:\Program Files\Microsoft Visual Studio\18\Community\VC\Auxiliary\Build\vcvarsall.bat",
        r"C:\Program Files\Microsoft Visual Studio\2022\Community\VC\Auxiliary\Build\vcvarsall.bat",
        r"C:\Program Files\Microsoft Visual Studio\2022\Professional\VC\Auxiliary\Build\vcvarsall.bat",
        r"C:\Program Files\Microsoft Visual Studio\2022\Enterprise\VC\Auxiliary\Build\vcvarsall.bat",
        r"C:\Program Files (x86)\Microsoft Visual Studio\2019\Community\VC\Auxiliary\Build\vcvarsall.bat",
        r"C:\Program Files (x86)\Microsoft Visual Studio\2019\BuildTools\VC\Auxiliary\Build\vcvarsall.bat",
    ]
    for p in candidates:
        if os.path.exists(p):
            return p
    return ""


def build_extensions():
    """执行 Cython 编译流水线"""
    print("=" * 65)
    print("  Coil-Architect Pro - Cython 原生机器码 (.pyd) 编译流水线")
    print("=" * 65)

    setup_content = """# Auto-generated by build_cython.py
from setuptools import setup, Extension
from Cython.Build import cythonize

ext_modules = [
    Extension("src.core.models", ["src/core/models.py"]),
    Extension("src.core.physics_engine", ["src/core/physics_engine.py"]),
    Extension("src.core.license_manager", ["src/core/license_manager.py"]),
]

setup(
    name="coil_architect_core",
    ext_modules=cythonize(
        ext_modules,
        compiler_directives={"language_level": "3", "always_allow_keywords": True},
        quiet=False
    )
)
"""
    tmp_setup = _ROOT_DIR / "_temp_setup_cython.py"
    tmp_setup.write_text(setup_content, encoding="utf-8")

    vcvars = find_vcvarsall()
    cmd = f'python "{tmp_setup}" build_ext --inplace'
    if vcvars and sys.platform == "win32":
        print(f"[MSVC] 正在载入 MSVC 64位编译环境: {vcvars}")
        full_cmd = f'call "{vcvars}" x64 && {cmd}'
    else:
        full_cmd = cmd

    try:
        print(f"[Build] 执行编译命令: {cmd}")
        res = subprocess.run(full_cmd, shell=True, check=True)
        print("[Build] 编译成功完成！")
    except subprocess.CalledProcessError as e:
        print(f"[Error] 编译失败: {e}", file=sys.stderr)
        return False
    finally:
        if tmp_setup.exists():
            tmp_setup.unlink(missing_ok=True)

    # 清理中间文件
    clean_artifacts()
    return True


def clean_artifacts():
    """依据规范 01.四 清理中间生成的 .c 文件与 build 临时目录"""
    print("[Clean] 清理临时构建产物...")
    core_dir = _ROOT_DIR / "src" / "core"
    for c_file in core_dir.glob("*.c"):
        try:
            c_file.unlink(missing_ok=True)
            print(f"  已清理中间 C 文件: {c_file.name}")
        except Exception:
            pass

    build_dir = _ROOT_DIR / "build"
    if build_dir.exists():
        try:
            shutil.rmtree(build_dir, ignore_errors=True)
            print("  已清理 build/ 临时目录")
        except Exception:
            pass


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    success = build_extensions()
    if success:
        print("\n[OK] [SUCCESS] 核心模块已成功编译为 Windows 原生 C 机器码动态库 (.pyd)！")
        print("  - src/core/models.*.pyd")
        print("  - src/core/physics_engine.*.pyd")
        print("  - src/core/license_manager.*.pyd")
        print("  在制作最终商业交付版打包时，可安全物理删除对应的 .py 源码文件。")
    else:
        sys.exit(1)

